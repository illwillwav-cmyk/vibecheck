/** The text of the first <string> that follows a given <key> in a plist. */
juce::String plistValueAfterKey (const juce::String& plist, const juce::String& key)
{
    const auto keyAt = plist.indexOf ("<key>" + key + "</key>");

    if (keyAt < 0)
        return {};

    const auto open = plist.indexOf (keyAt, "<string>");
    const auto close = plist.indexOf (keyAt, "</string>");

    if (open < 0 || close < open)
        return {};

    return plist.substring (open + 8, close).trim();
}

/** The names a plugin's own code lives in, read from Itanium-mangled symbols: the first name
    inside the mangling is the class or namespace. Framework scopes are left out, so what remains
    is what the author (or generator) named. */
juce::StringArray userScopes (const juce::StringArray& symbols)
{
    static const juce::StringArray framework { "juce", "Steinberg", "VST3", "Vst", "Presonus", "VSTGUI", "std", "__cxxabiv1",
                                                "__gnu_cxx", "choc", "clap", "farbot", "moodycamel" };
    juce::StringArray scopes;
    std::set<juce::String> seen;

    for (const auto& symbol : symbols)
    {
        if (! symbol.startsWith ("__ZN"))
            continue;

        auto position = 4;

        while (position < symbol.length() && (symbol[position] == 'r' || symbol[position] == 'V' || symbol[position] == 'K'))
            ++position;

        int length = 0, digits = 0;

        while (position + digits < symbol.length() && juce::CharacterFunctions::isDigit (symbol[position + digits]) && digits < 3)
            length = length * 10 + (symbol[position + digits++] - '0');

        if (digits == 0 || length <= 0 || position + digits + length > symbol.length())
            continue;

        const auto name = symbol.substring (position + digits, position + digits + length);

        if (! framework.contains (name) && seen.insert (name).second)
            scopes.add (name);
    }

    return scopes;
}

/** Domains that appear in a binary because of the frameworks inside it, not the author. */
bool isFrameworkDomain (const juce::String& url)
{
    for (const auto* domain : { "juce.com", "steinberg", "apple.com", "w3.org", "github.com/juce", "github.com/steinberg",
                                 "gnu.org", "unicode.org", "mozilla", "boost.org", "llvm.org", "openssl", "curl.se", "sqlite.org",
                                 "zlib", "libpng", "ietf.org", "creativecommons", "xiph.org", "xmlsoft", "freetype", "ogg", "flac",
                                 "mp3", "schemas.", "ns.adobe", "purl.org", "example.com", "localhost", "127.0.0.1", "xml.org",
                                 "docs.microsoft", "msdn", "khronos.org", "opengl", "python.org", "gcc.gnu", "isocpp" })
        if (url.containsIgnoreCase (domain))
            return true;

    return false;
}

bool anyContains (const juce::StringArray& haystack, const juce::String& needle)
{
    for (const auto& entry : haystack)
        if (entry.contains (needle))
            return true;

    return false;
}

bool anyEquals (const juce::StringArray& haystack, const juce::String& needle)
{
    for (const auto& entry : haystack)
        if (entry == needle)
            return true;

    return false;
}

juce::String firstMatch (const juce::StringArray& haystack, const juce::StringArray& needlesLowerCase)
{
    for (const auto& entry : haystack)
    {
        const auto lower = entry.toLowerCase();

        for (const auto& needle : needlesLowerCase)
            if (lower.contains (needle))
                return entry.substring (0, 120);
    }

    return {};
}
